#!/usr/bin/env node
// Refuse to publish anything that is not code, our own method docs, or
// primary-source evidence from a public register.
//
// This repo is public: a commit is a publication. That rule was written down
// repeatedly and kept failing, because a .gitignore is a BLOCKLIST — it bans
// the formats someone thought of last time, and the next document type walks
// straight past it. An unlodged submission draft, a contact list with named
// individuals' email addresses, an officer-provided spreadsheet and sixteen
// copyrighted journal PDFs all reached the public tree that way.
//
// So this is an ALLOWLIST. The default is no. A path that does not match a rule
// below is refused, and the fix is to move it out of the repo, not to add a
// rule — unless it genuinely belongs in one of the categories below.
//
//   node scripts/check-allowlist.mjs --staged   # what is about to be committed
//   node scripts/check-allowlist.mjs --tree     # everything currently tracked
//
// Exit 0 clean, 1 if anything is refused.

import { execSync } from 'node:child_process';

// --- 1. Code -----------------------------------------------------------------
const CODE = [
  /^src\//,
  /^pipeline\//,
  /^public\//,
  /^scripts\//,
  /^\.github\//,
  /^\.githooks\//,
  /^\.vscode\//,
];

// Top-level project files, by exact name or unambiguous config extension.
const ROOT_FILES = [
  /^\.gitignore$/,
  /^\.env\.example$/,
  /^\.dev\.vars\.example$/,
  /^package(-lock)?\.json$/,
  /^tsconfig\.json$/,
  /^wrangler\.jsonc$/,
  /^[\w.-]+\.config\.(ts|mjs|js)$/,
  /^[\w.-]+\.d\.ts$/,
  /^LICENSE$/,
  /^README\.md$/,
  /^CITATION\.cff$/,
];

// --- 2. Method documents we authored ----------------------------------------
// Markdown under docs/ is ours: methodology, guides, audit write-ups, changelog.
// Generators and the diagrams/citation data they emit come with them.
const METHOD = [
  /^docs\/[\w.-]+\.md$/,
  /^docs\/[\w.-]+\.(py|json|jsonl|ris|svg|png)$/,
];

// --- 3. Primary-source evidence from public registers ------------------------
// The audited permits and delegate reports, the text extracts behind negative
// claims, and the government API specs. This is the audit record — the thing
// the project asks planning systems to produce — so it belongs in public.
const EVIDENCE = [
  /^docs\/disclosure-audit\//,
  /^docs\/evidence-cache\//,
  /^docs\/Online [\w. ]+\.pdf$/,
];

// Denials that beat every rule above, so a stray file cannot slip in by sitting
// in an allowed directory. docs/internal/ is the working area by convention.
const NEVER = [
  { re: /^docs\/internal\//, why: 'docs/internal/ is the local working area' },
  { re: /^lit review\//, why: 'third-party literature is not ours to redistribute' },
  { re: /^content updates\//, why: 'working material, not published output' },
  { re: /\.(docx?|xlsx?|pptx?|pages|numbers|key)$/i, why: 'office documents are never published from this repo' },
];

// --- 4. Derived snapshots of our own tracker ---------------------------------
// zenodo/ is regenerated by pipeline/export-zenodo.ts and committed each run.
// Nothing in it is hand-typed: it is the published deposit bundle, and keeping
// the series in git is what makes change measurable rather than asserted.
// Deliberately narrow — the two CSVs and the generated docs, nothing else.
const SNAPSHOT = [
  /^zenodo\/[\w.-]+\.(csv|md)$/,
];

const RULES = [...CODE, ...ROOT_FILES, ...METHOD, ...EVIDENCE, ...SNAPSHOT];

function classify(path) {
  for (const { re, why } of NEVER) if (re.test(path)) return { ok: false, why };
  if (RULES.some((re) => re.test(path))) return { ok: true };
  return { ok: false, why: 'not code, not a method document we wrote, not register evidence, not a derived snapshot' };
}

function paths(mode) {
  const cmd =
    mode === '--staged'
      ? 'git diff --cached --name-only --diff-filter=ACMR'
      : 'git ls-files';
  return execSync(cmd, { encoding: 'utf8' }).split('\n').filter(Boolean);
}

const mode = process.argv.includes('--tree') ? '--tree' : '--staged';
const refused = paths(mode)
  .map((p) => ({ p, ...classify(p) }))
  .filter((r) => !r.ok);

if (refused.length === 0) process.exit(0);

const where = mode === '--staged' ? 'staged for commit' : 'tracked in this repo';
console.error(`\n  REFUSED — ${refused.length} file(s) ${where} are not publishable.\n`);
console.error('  This repository is PUBLIC. A commit here is a publication.\n');
for (const { p, why } of refused) console.error(`    ${p}\n      ${why}`);
console.error(`
  Only these may be committed:
    1. Code — src/ pipeline/ public/ scripts/ .github/ and project config
    2. Method documents we wrote — docs/*.md and the generators beside them
    3. Primary-source evidence from public registers — docs/disclosure-audit/,
       docs/evidence-cache/, government API specs
    4. Derived snapshots of our own tracker — zenodo/*.csv and zenodo/*.md

  Everything else stays local, whatever its format. Drafts, submissions,
  contacts, third-party literature, spreadsheets, screenshots, scraped pages,
  internal QA, and any working file that QUOTES one of those.

  To fix: move the file to docs/internal/ (gitignored) or out of the repo, then
    git restore --staged <path>

  Do not add a rule to this script to get past it unless the file genuinely
  belongs in one of the categories above.
`);
process.exit(1);
